export function translateAnswer(text, lang) {
  if (!lang || lang === 'en' || !text) return text;
  const dict = PHRASE_TRANSLATIONS[lang];
  if (!dict) return text;
  let res = text;
  for (const [en, local] of dict) {
    if (res.includes(en)) {
      res = res.replaceAll(en, local);
    }
  }
  return res;
}

export function translateBasedOn(basedOn, lang) {
  if (!lang || lang === 'en' || !basedOn) return basedOn;
  const prefix = {
    de: 'Basierend auf: ',
    fr: 'Basé sur : ',
    pt: 'Com base em: ',
    es: 'Basado en: ',
    id: 'Berdasarkan: ',
    ar: 'بناءً على: ',
    hi: 'आधार: ',
  }[lang] || 'Based on: ';
  
  const content = basedOn.replace(/^Based on:\s*/i, '');
  return prefix + translateAnswer(content, lang);
}
